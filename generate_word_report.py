def add_formal_table(table_num_str, table_title, headers, rows, col_widths_cm=None):
    # Caption above table
    p_cap = doc.add_paragraph()
    p_cap.paragraph_format.space_before = Pt(8)
    p_cap.paragraph_format.space_after = Pt(3)
    p_cap.paragraph_format.keep_with_next = True
    r_b = p_cap.add_run(f"{table_num_str} ")
    set_run_font(r_b, size_pt=15, bold=True)
    r_t = p_cap.add_run(table_title)
    set_run_font(r_t, size_pt=15)

    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = 'Table Grid'

    # Header row
    hdr_cells = table.rows[0].cells
    for i, h_text in enumerate(headers):
        hdr_cells[i].vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="EAEAEA"/>')
        hdr_cells[i]._tc.get_or_add_tcPr().append(shd)
        p = hdr_cells[i].paragraphs[0]
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(2)
        r = p.add_run(h_text)
        set_run_font(r, size_pt=15, bold=True)

    # Data rows
    for r_idx, row_data in enumerate(rows):
        row_cells = table.rows[r_idx + 1].cells
        for c_idx, cell_text in enumerate(row_data):
            p = row_cells[c_idx].paragraphs[0]
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.line_spacing = 1.1
            r = p.add_run(cell_text)
            set_run_font(r, size_pt=14.5, bold=(c_idx == 0))

    if col_widths_cm:
        for row in table.rows:
            for idx, w_cm in enumerate(col_widths_cm):
                row.cells[idx].width = Cm(w_cm)

    p_after = doc.add_paragraph()
    p_after.paragraph_format.space_after = Pt(2)
    return table

