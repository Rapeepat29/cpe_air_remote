def add_bullet_item(bold_prefix, text_rest, level=0):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.75 + level * 0.6)
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.15
    bullet_char = "• " if level == 0 else "- "
    r0 = p.add_run(bullet_char)
    set_run_font(r0, size_pt=16, bold=True)
    if bold_prefix:
        r1 = p.add_run(bold_prefix)
        set_run_font(r1, size_pt=16, bold=True)
    if text_rest:
        r2 = p.add_run(text_rest)
        set_run_font(r2, size_pt=16)
    return p

